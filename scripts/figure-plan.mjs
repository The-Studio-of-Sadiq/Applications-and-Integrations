#!/usr/bin/env node
// Collect the <!-- FIGURE ... --> markers from every chapter into FIGURES.md.
//
//   node scripts/figure-plan.mjs            # rewrite FIGURES.md
//   node scripts/figure-plan.mjs --check    # only report counts and malformed markers
import { writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { ROOT, BOOK_TITLE, listParts, figureMarkers } from "../lib/book.mjs";

const check = process.argv.includes("--check");
const cell = (s = "") => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

const chapters = listParts().filter((p) => p.kind === "chapter");
const problems = [];
const kinds = {};
let total = 0;
const blocks = [];

for (const ch of chapters) {
  const figs = figureMarkers(ch);
  total += figs.length;
  for (const f of figs) {
    kinds[f.kind] = (kinds[f.kind] ?? 0) + 1;
    if (!f.number || !f.path || !f.kind || !f.caption) problems.push(`${ch.relPath}:${f.line} malformed marker`);
    else if (!f.number.startsWith(`${ch.id}.`)) problems.push(`${ch.relPath}:${f.line} figure ${f.number} is numbered for another chapter`);
  }
  const rows = figs.map((f) => {
    const done = f.path && existsSync(join(ROOT, f.path)) ? "✔" : "";
    return `| ${cell(f.number)} | ${cell(f.kind)} | ${cell(f.caption)} | ${cell(f.content)} | [L${f.line}](${encodeURI(ch.relPath)}#L${f.line}) | \`${cell(f.path)}\` ${done} |`;
  });
  blocks.push(
    `## ${ch.title}\n\n` +
      (rows.length
        ? `| No. | Kind | Caption | What to draw | Placed at | File |\n|---|---|---|---|---|---|\n${rows.join("\n")}\n`
        : "_No figures planned._\n"),
  );
}

const summary = Object.entries(kinds)
  .sort((a, b) => b[1] - a[1])
  .map(([k, n]) => `| ${k} | ${n} |`)
  .join("\n");

console.error(`${total} planned figure(s) across ${chapters.length} chapter(s).`);
if (problems.length) console.error(`${problems.length} problem(s):\n  ${problems.join("\n  ")}`);

if (!check) {
  writeFileSync(
    join(ROOT, "FIGURES.md"),
    `# Figure Plan — ${BOOK_TITLE}

Generated by \`node scripts/figure-plan.mjs\` from the \`<!-- FIGURE ... -->\` markers in the chapters. Edit the markers, not this file.

Each marker sits at the exact point in the chapter where the figure belongs. To add a figure, draw it to the listed path and replace the marker with an image line plus italic caption (see [CONTRIBUTING.md](CONTRIBUTING.md#figure-markers)). A ✔ means the file already exists.

**${total} figures planned.**

| Kind | Count |
|---|---|
${summary}

${blocks.join("\n")}`,
  );
  console.error("Wrote FIGURES.md");
}
process.exitCode = problems.length ? 1 : 0;
